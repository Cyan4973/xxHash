#!/bin/sh
# Generates xxhash.h from the source units in lib/.
#
# The root file is copied verbatim, except for lines of the form
#     #include "unit.h"
# which are replaced by the content of unit.h (path relative to the including
# file), minus its leading license block. Expansion is recursive.
# Each unit must start with a license block (/* ... */, mentioning Copyright
# and BSD 2-Clause License), followed by exactly one empty line.
# Each file must have balanced #if / #endif.
# All *.h files in the root's directory must be used (included or excluded).
# Excluding a unit also excludes the units it includes.
# Variants are generated by excluding units (-x), and defining the build macros
# (-D) which remove the same code from the remaining units.
#
# The result keeps the license block of the root, followed by a note telling
# it is generated. By default, comments are removed, except the documentation
# of declarations in declaration units (*_api.h, *_static.h), which IDEs display.
#
# Requires only a POSIX shell and a POSIX awk.

set -eu

LC_ALL=C
export LC_ALL
AWK=${AWK:-awk}
prog=amalgamate.sh

usage() {
    cat >&2 <<EOF
Usage: $0 [--comments MODE] [-x UNIT]... [-D MACRO]... [-o FILE | --check FILE | --where N] ROOT

  (default)       write the result to stdout
  -o FILE         write the result to FILE (only touched if content changes)
  --check FILE    exit 1 if FILE differs from the result (never writes)
  --where N       tell which unit, and which line, line N of the result comes from
  -x UNIT         exclude UNIT (name as written in #include) from the result
  -D MACRO        define build MACRO at the beginning of the result
                  (after the license block of ROOT)
  --comments MODE api (default): keep only the documentation of declarations
                  in declaration units (*_api.h, *_static.h)
                  none: remove all comments
                  all: keep all comments (e.g. to generate documentation)
EOF
    exit 2
}

die() {
    echo "$prog: error: $*" >&2
    exit 1
}

out='' check='' where='' excludes='' defines='' comments=api root=''
while [ $# -gt 0 ]; do
    case $1 in
    -o)       [ $# -ge 2 ] || usage; out=$2; shift 2 ;;
    --check)  [ $# -ge 2 ] || usage; check=$2; shift 2 ;;
    --where)  [ $# -ge 2 ] || usage; where=$2; shift 2 ;;
    -x)       [ $# -ge 2 ] || usage; excludes="$excludes $2"; shift 2 ;;
    -D)       [ $# -ge 2 ] || usage
              case $2 in
              ''|[0-9]*|*[!A-Za-z0-9_]*) die "-D expects a macro name: $2" ;;
              esac
              defines="$defines $2"; shift 2 ;;
    --comments) [ $# -ge 2 ] || usage
              case $2 in
              api|none|all) comments=$2 ;;
              *) die "--comments expects api, none or all: $2" ;;
              esac
              shift 2 ;;
    -h|--help) usage ;;
    -*)       die "unknown option: $1" ;;
    *)        [ -z "$root" ] || die "only one ROOT file can be given"; root=$1; shift ;;
    esac
done
[ -n "$root" ] || usage
[ -f "$root" ] || die "cannot read $root"
[ -z "$check" ] || [ -z "$out" ] || die "--check and -o are mutually exclusive"
[ -z "$check" ] || [ -f "$check" ] || die "cannot read $check"
if [ -n "$where" ]; then
    [ -z "$out$check" ] || die "--where cannot be combined with -o or --check"
    case $where in
    ''|*[!0-9]*) die "--where expects a line number" ;;
    esac
fi

# list all units, using the same path syntax as the awk script
rootdir=$(dirname "$root")
srcname=$(basename "$(CDPATH='' cd "$rootdir" && pwd)")   # e.g. lib, for the generated note
units=
if [ "$rootdir" = "." ]; then
    for f in *.h; do [ ! -f "$f" ] || units="$units $f"; done
else
    for f in "$rootdir"/*.h; do [ ! -f "$f" ] || units="$units $f"; done
fi

generate() {
    $AWK -v prog="$prog" -v root="$root" -v excludes="$excludes" -v defines="$defines" \
           -v allunits="$units" -v where="$where" -v comments="$comments" -v srcdir="$srcname" '
    function fail(msg) {
        if (!err) print prog ": error: " msg | "cat 1>&2"
        err = 1
    }

    function emit(line, file, lineno) {
        outn++
        if (where == "") print line
        else if (outn == where) { wherefile = file; whereline = lineno; whatline = line }
    }

    # note following the license block of the root, then macros of -D
    function preamble(    k) {
        emit("", "(generated)", 0)
        emit("/*", "(generated)", 0)
        emit(" * This file is generated by build/amalgamate.sh,", "(generated)", 0)
        emit(" * from the source units in the " srcdir "/ directory of the xxHash source repository.", "(generated)", 0)
        emit(" * These units are the source of truth: modify them instead of this file.", "(generated)", 0)
        if (comments == "api") {
            emit(" * Only the documentation of public declarations is kept here:", "(generated)", 0)
            emit(" * comments and complete documentation are in the source units.", "(generated)", 0)
        }
        if (comments == "none")
            emit(" * Comments and documentation are only present in the source units.", "(generated)", 0)
        emit(" */", "(generated)", 0)
        if (ndefines) {
            emit("", "(-D)", 0)
            emit("/* This variant of xxhash.h is generated with:" defines " */", "(-D)", 0)
            for (k = 1; k <= ndefines; k++) {
                emit("#ifndef " deflist[k], "(-D)", 0)
                emit("#  define " deflist[k], "(-D)", 0)
                emit("#endif", "(-D)", 0)
            }
        }
        lastblank = 0
    }

    # removes comments from a line, keeping string and character literals;
    # a comment is replaced by a space, so that it cannot join tokens.
    # With keepdoc, documentation of members at the end of a line (/*!< ... */) is kept.
    function uncomment(line, keepdoc,    out, pos, cnt, c, nxt, q, e) {
        if (!incomment && !index(line, "/")) return line
        out = ""; cnt = length(line); pos = 1
        while (pos <= cnt) {
            c = substr(line, pos, 1)
            nxt = (pos < cnt) ? substr(line, pos + 1, 1) : ""
            if (incomment) {
                if (c == "*" && nxt == "/") {
                    incomment = 0; pos += 2
                    if (out != "" && out !~ /[ \t]$/) out = out " "
                } else pos++
                continue
            }
            if (c == "/" && nxt == "*") {
                if (keepdoc && pos + 3 < cnt && substr(line, pos, 4) == "/*!<" \
                    && (e = index(substr(line, pos + 4), "*/"))) {
                    out = out substr(line, pos, e + 5); pos += e + 5
                    continue
                }
                incomment = 1; pos += 2
                continue
            }
            if (c == "/" && nxt == "/") break
            out = out c; pos++
            if (c == "\"" || c == "\047") {
                q = c
                while (pos <= cnt) {
                    c = substr(line, pos, 1); out = out c; pos++
                    if (c == "\\" && pos <= cnt) { out = out substr(line, pos, 1); pos++ }
                    else if (c == q) break
                }
            }
        }
        return out
    }

    # emits a line of code, without its comments (unless --comments all):
    # lines left empty are removed, consecutive empty lines are merged,
    # and macros continued by a final backslash are preserved.
    # With keepdoc, a documentation block (/*! or /** on its own lines)
    # is kept if it is followed by a declaration.
    function output(line, file, lineno, keepdoc,    s, blank, k) {
        if (comments == "all") { emit(line, file, lineno); return }
        if (indoc) { docline(line, file, lineno, keepdoc); return }
        if (keepdoc && !incomment && !lastcont \
            && line ~ /^[ \t]*\/\*(!|\*([^*\/]|$))/ && line !~ /^[ \t]*\/\*!</) {
            ndoc = 0; pending = 0; indoc = 1
            docline(line, file, lineno, keepdoc)
            return
        }
        blank = (!incomment && line ~ /^[ \t]*$/)
        s = uncomment(line, keepdoc)
        sub(/[ \t]+$/, "", s)
        if (s == "") {
            if (pending) return
            if (lastcont) { emit("", file, lineno); lastcont = 0; lastblank = 1 }
            else if (blank && !lastblank) { emit("", file, lineno); lastblank = 1 }
            return
        }
        if (pending) {
            pending = 0
            if (s !~ /^[ \t]*#[ \t]*(if|ifdef|ifndef|elif|else|endif|include|undef|pragma|error|warning|line)([^a-z_]|$)/) {
                if (!lastblank && outn) emit("", "(blank)", 0)
                for (k = 1; k <= ndoc; k++) emit(docl[k], docf[k], docn[k])
                lastblank = 0
            }
            ndoc = 0
        }
        if (lastcont && s ~ /^[ \t]*\\$/) return
        emit(s, file, lineno)
        lastblank = 0; lastcont = (s ~ /\\$/)
    }

    # collects a line of a documentation block
    function docline(line, file, lineno, keepdoc,    rest) {
        ndoc++; docl[ndoc] = line; docf[ndoc] = file; docn[ndoc] = lineno
        if (!index(line, "*/")) return
        indoc = 0
        rest = line; sub(/^.*\*\//, "", rest)
        if (rest ~ /^[ \t]*$/) { pending = 1; return }
        ndoc = 0                    # code follows the block: process it alone
        output(rest, file, lineno, keepdoc)
    }

    # excluded unit: its nested units are excluded too
    function skip(file,    dir, line, rc, name, path) {
        if (file in seen) { fail(file ": included more than once"); return }
        seen[file] = 1
        dir = file
        if (!sub(/\/[^\/]*$/, "", dir)) dir = "."
        while ((rc = (getline line < file)) > 0) {
            if (line !~ /^#include "[^"]+"/) continue
            name = line; sub(/^#include "/, "", name); sub(/".*$/, "", name)
            path = (dir == ".") ? name : dir "/" name
            if (name in excluded) exused[name] = 1
            skip(path)
        }
        if (rc < 0) fail("cannot read " file)
        close(file)
    }

    function expand(file, depth,    dir, line, lineno, rc, state, hascopy, hasbsd, bal, name, rest, path, probe, keepdoc) {
        if (file in seen) { fail(file ": included more than once"); return }
        seen[file] = 1
        dir = file
        if (!sub(/\/[^\/]*$/, "", dir)) dir = "."
        state = (depth > 0)   # 1: expect license block start, 2: in license block, 3: expect empty line, 0: body
        keepdoc = (comments == "api" && file ~ /_(api|static)\.h$/)
        lineno = 0; bal = 0; hascopy = 0; hasbsd = 0
        while ((rc = (getline line < file)) > 0) {
            lineno++
            sub(/\r$/, "", line)
            if (state == 1) {
                if (line != "/*") {
                    fail(file ":" lineno ": a unit must start with its license block")
                    break
                }
                state = 2
                continue
            }
            if (state == 2) {
                if (index(line, "Copyright")) hascopy = 1
                if (index(line, "BSD 2-Clause License")) hasbsd = 1
                if (line == " */") {
                    if (!hascopy || !hasbsd) {
                        fail(file ":" lineno ": license block lacks Copyright or BSD 2-Clause License")
                        break
                    }
                    state = 3
                }
                continue
            }
            if (state == 3) {
                if (line != "") {
                    fail(file ":" lineno ": license block must be followed by exactly one empty line")
                    break
                }
                state = 0
                continue
            }
            if (line ~ /^[ \t]*#[ \t]*if/) bal++
            if (line ~ /^[ \t]*#[ \t]*endif/ && --bal < 0) {
                fail(file ":" lineno ": #endif without #if")
                break
            }
            if (line ~ /^[ \t]*#[ \t]*include[ \t]*"/) {
                pending = 0; ndoc = 0
                if (line !~ /^#include "[^"]+"/) {
                    fail(file ":" lineno ": unit inclusion must be written exactly as: #include \"unit.h\"")
                    break
                }
                name = line; sub(/^#include "/, "", name)
                rest = name; sub(/^[^"]*"/, "", rest); sub(/".*$/, "", name)
                if (rest !~ /^[ \t]*$/ && rest !~ /^[ \t]*\/\*.*\*\/[ \t]*$/) {
                    fail(file ":" lineno ": unexpected text after #include")
                    break
                }
                path = (dir == ".") ? name : dir "/" name
                if (name in excluded) {
                    exused[name] = 1
                    skip(path)
                    continue
                }
                if ((getline probe < path) < 0) {
                    fail(file ":" lineno ": cannot read " path)
                    break
                }
                close(path)
                expand(path, depth + 1)
                if (err) break
                continue
            }
            if (depth == 0 && !licensed) {
                emit(line, file, lineno)    # license block of the root, kept verbatim
                if (line == " */") { licensed = 1; preamble() }
                continue
            }
            output(line, file, lineno, keepdoc)
        }
        pending = 0; ndoc = 0
        if (rc < 0) fail("cannot read " file)
        close(file)
        if (!err && state) fail(file ": incomplete license block")
        if (!err && bal) fail(file ": " bal " unterminated #if")
        if (!err && (incomment || indoc)) fail(file ": unterminated comment")
    }

    BEGIN {
        err = 0; outn = 0; wherefile = ""; licensed = 0; incomment = 0; lastblank = 0; lastcont = 0
        indoc = 0; pending = 0; ndoc = 0
        ndefines = split(defines, deflist, " ")
        n = split(excludes, list, " ")
        for (i = 1; i <= n; i++) excluded[list[i]] = 1
        if (where != "") where += 0
        expand(root, 0)
        for (u in excluded)
            if (!err && !(u in exused)) fail("-x " u ": no such #include")
        if (!err && !licensed) fail(root ": cannot find the end of its license block")
        n = split(allunits, list, " ")
        for (i = 1; i <= n; i++)
            if (!err && !(list[i] in seen)) fail(list[i] ": unit is never included")
        if (!err && where != "") {
            if (wherefile == "") fail("line " where " is beyond the end of the result (" outn " lines)")
            else print wherefile ":" whereline ": " whatline
        }
        exit err
    }'
}

tmp=
cleanup() {
    [ -z "$tmp" ] || rm -f "$tmp"
}
trap cleanup EXIT
trap 'exit 2' HUP INT TERM

# succeed if files $1 and $2 are identical (cmp is not always available, e.g. on MSYS2)
same() {
    # shellcheck disable=SC2016 # awk script
    [ "$(wc -c < "$1")" = "$(wc -c < "$2")" ] &&
    $AWK 'NR == FNR { a[NR] = $0; next } a[FNR] "" != $0 "" { exit 1 }' "$1" "$2"
}

replace() {
    mv -f "$tmp" "$out"
    tmp=
    echo "$prog: updated $out" >&2
}

# tell where FILE starts to differ from the result (in $tmp), and which unit line is expected there
firstdiff() {
    # shellcheck disable=SC2016 # awk script
    first=$($AWK 'NR == FNR { a[NR] = $0; next }
                  !(FNR in a) || a[FNR] "" != $0 "" { print FNR; found = 1; exit }
                  END { if (!found) print FNR + 1 }' "$tmp" "$1")
    expected=$(where=$first; generate 2>/dev/null) || expected=''
    printf '%s: first difference: %s:%s%s\n' "$prog" "$1" "$first" "${expected:+, expected from $expected}" >&2
}

if [ -n "$check" ]; then
    tmp="$check.tmp.$$"
    generate > "$tmp"
    if ! same "$tmp" "$check"; then
        echo "$prog: $check is not up to date with $rootdir/" >&2
        firstdiff "$check"
        echo "$prog: $check is generated: changes must be made in the units of $rootdir/," >&2
        echo "$prog: then 'make amalgamate' regenerates $check (overwriting direct edits): commit both" >&2
        if command -v diff > /dev/null 2>&1; then
            diff -u "$check" "$tmp" | head -n 40 >&2 || true
        fi
        exit 1
    fi
elif [ -n "$out" ]; then
    tmp="$out.tmp.$$"
    generate > "$tmp"
    if [ -f "$out" ] && same "$tmp" "$out"; then
        rm -f "$tmp"
        tmp=
    else
        replace
    fi
else
    generate
fi
